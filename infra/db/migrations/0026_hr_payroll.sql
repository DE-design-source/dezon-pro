comment on column hr_payroll_settings.updated_by is 'User who saved last; set null if the user is deleted.';
comment on column hr_payroll_settings.updated_at is 'Last change time (set by the service).';

create table hr_pay_adjustments (
  id              bigint      generated by default as identity,
  employee_id     bigint      not null,
  pay_month       date        not null,
  adjustment_kind text        not null,
  label           text        not null,
  amount_vnd      numeric(18,0) not null,
  created_by      uuid,
  created_at      timestamptz not null default now(),
  constraint pk_hr_pay_adjustments primary key (id),
  constraint fk_hr_pay_adjustments_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint fk_hr_pay_adjustments_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_hr_pay_adjustments_pay_month check (extract(day from pay_month) = 1),
  constraint ck_hr_pay_adjustments_adjustment_kind check (adjustment_kind in ('bonus', 'penalty', 'sales')),
  constraint ck_hr_pay_adjustments_label check (label <> ''),
  constraint ck_hr_pay_adjustments_amount_vnd check (amount_vnd > 0)
);
-- Phục vụ: khoá ngoại employee_id cascade (xoá nhân sự).
create index idx_hr_pay_adjustments_employee_id on hr_pay_adjustments (employee_id);

comment on table hr_pay_adjustments is 'Bonus / penalty / sales amount of an employee for one pay month (child of hr_employees).';
comment on column hr_pay_adjustments.id is 'Primary key.';
comment on column hr_pay_adjustments.employee_id is 'Employee; rows are deleted with it.';
comment on column hr_pay_adjustments.pay_month is 'Pay month, always the first day of the month.';
comment on column hr_pay_adjustments.adjustment_kind is 'bonus (added) / penalty (deducted) / sales (sales amount, commission = amount x commission rate).';
comment on column hr_pay_adjustments.label is 'What it is for.';
comment on column hr_pay_adjustments.amount_vnd is 'Amount, VND, always positive (the kind gives the sign).';
comment on column hr_pay_adjustments.created_by is 'User who entered it; set null if the user is deleted.';
comment on column hr_pay_adjustments.created_at is 'Row creation time.';

create table hr_payroll_runs (
  id                   bigint      generated by default as identity,
  company_id           uuid        not null,
  pay_month            date        not null,
  run_status           text        not null default 'draft',
  is_attendance_closed boolean     not null default false,
  payslips             jsonb,
  approved_at          timestamptz,
  approved_by          uuid,
  paid_at              timestamptz,
  updated_at           timestamptz not null default now(),
  constraint pk_hr_payroll_runs primary key (id),
  constraint uq_hr_payroll_runs_company_id_pay_month unique (company_id, pay_month),
  constraint fk_hr_payroll_runs_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_payroll_runs_approved_by foreign key (approved_by) references users (id) on delete set null,
  constraint ck_hr_payroll_runs_pay_month check (extract(day from pay_month) = 1),
  constraint ck_hr_payroll_runs_run_status check (run_status in ('draft', 'approved', 'paid')),
  constraint ck_hr_payroll_runs_payslips check ((run_status = 'draft') = (payslips is null) and (payslips is null or jsonb_typeof(payslips) = 'object')),
  constraint ck_hr_payroll_runs_paid_at check ((run_status = 'paid') = (paid_at is not null))
);
-- uq_hr_payroll_runs_company_id_pay_month phục vụ: kỳ lương của công ty theo tháng (hr/payroll.go) + 1 kỳ / tháng.

comment on table hr_payroll_runs is 'Pay period of a company for one month: attendance closing, approval and payment (tenant-owned root table). No row = draft, attendance open.';
comment on column hr_payroll_runs.id is 'Primary key.';
comment on column hr_payroll_runs.company_id is 'Owning company; set from the login session, never from the client.';
comment on column hr_payroll_runs.pay_month is 'Pay month, always the first day of the month.';
comment on column hr_payroll_runs.run_status is 'draft / approved / paid. Adjustments of the month are locked unless draft.';
comment on column hr_payroll_runs.is_attendance_closed is 'Attendance of the month is closed: attendance records of that month can no longer be written.';
comment on column hr_payroll_runs.payslips is 'Snapshot taken at approval, read/written whole: {"<employee id>": {"emp": {...}, "att": {...}, "p": {...}}} - attendance summary and pay breakdown computed by the frontend (calcPay). Null while draft.';
comment on column hr_payroll_runs.approved_at is 'Approval time; kept when paid, cleared on reopen.';
