create table hr_payroll_settings (
  id          bigint      generated by default as identity,
  company_id  uuid        not null,
  config      jsonb       not null,
  updated_by  uuid,
  updated_at  timestamptz not null default now(),
  constraint pk_hr_payroll_settings primary key (id),
  constraint uq_hr_payroll_settings_company_id unique (company_id),
  constraint fk_hr_payroll_settings_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_payroll_settings_updated_by foreign key (updated_by) references users (id) on delete set null,
  constraint ck_hr_payroll_settings_config check (jsonb_typeof(config) = 'object')
);
-- uq_hr_payroll_settings_company_id phục vụ: đọc / ghi cấu hình của công ty (hr/payroll.go) + 1 dòng / công ty.

comment on table hr_payroll_settings is 'Payroll formula settings of a company, one row per company (tenant-owned root table). No row = frontend defaults.';
comment on column hr_payroll_settings.id is 'Primary key.';
comment on column hr_payroll_settings.company_id is 'Owning company; set from the login session, never from the client.';
