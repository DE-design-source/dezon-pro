do $$ begin
  if to_regclass('public.it_tickets') is not null or to_regclass('public.it_assets') is not null then
    raise exception '0048: bảng it_tickets / it_assets đã có';
  end if;
end $$;

create table it_tickets (
  id                 bigint      generated by default as identity,
  company_id         uuid        not null,
  title              text        not null,
  description        text        not null default '',
  priority           text        not null default 'medium',
  category           text        not null default 'other',
  status             text        not null default 'moi',
  deadline_date      date,
  requester_name     text        not null default '',
  requester_username text        not null default '',
  roles              jsonb       not null default '[]',
  images             jsonb       not null default '[]',
  stages             jsonb,
  tasks              jsonb,
  source             text        not null default 'manual',
  page_ref           text        not null default '',
  is_received        boolean     not null default false,
  progress_pct       smallint    not null default 0,
  created_by         uuid,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint pk_it_tickets primary key (id),
  constraint fk_it_tickets_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_it_tickets_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_it_tickets_title check (title <> ''),
  constraint ck_it_tickets_priority check (priority in ('urgent', 'high', 'medium', 'low')),
  constraint ck_it_tickets_category check (category in ('hardware', 'software', 'network', 'account', 'other')),
  constraint ck_it_tickets_status check (status in ('moi', 'dangxuly', 'chodoi', 'hoanthanh', 'dong')),
  constraint ck_it_tickets_source check (source in ('manual', 'report')),
  constraint ck_it_tickets_progress_pct check (progress_pct between 0 and 100),
  constraint ck_it_tickets_roles check (jsonb_typeof(roles) = 'array'),
  constraint ck_it_tickets_images check (jsonb_typeof(images) = 'array'),
  constraint ck_it_tickets_stages check (stages is null or jsonb_typeof(stages) = 'array'),
  constraint ck_it_tickets_tasks check (tasks is null or jsonb_typeof(tasks) = 'array')
);
-- Phục vụ: danh sách yêu cầu của công ty, mới nhất trước (backend/internal/modules/it/postgres.go: ListTickets).
create index idx_it_tickets_company_id_created_at on it_tickets (company_id, created_at desc);
-- Phục vụ: "Đã gửi" của người báo (ListTickets mine, lọc created_by) + khoá ngoại created_by.
create index idx_it_tickets_created_by on it_tickets (created_by);

