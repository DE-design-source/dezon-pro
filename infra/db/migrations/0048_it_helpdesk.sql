create table it_assets (
  id          bigint      generated by default as identity,
  company_id  uuid        not null,
  asset_name  text        not null,
  asset_type  text        not null default '',
  holder      text        not null default '',
  status      text        not null default 'active',
  note        text        not null default '',
  created_by  uuid,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint pk_it_assets primary key (id),
  constraint fk_it_assets_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_it_assets_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_it_assets_asset_name check (asset_name <> ''),
  constraint ck_it_assets_status check (status in ('active', 'maintenance', 'broken'))
);
-- Phục vụ: danh sách thiết bị của công ty (backend/internal/modules/it/postgres.go: ListAssets).
create index idx_it_assets_company_id on it_assets (company_id);
-- Phục vụ: khoá ngoại created_by (xoá tài khoản -> set null không quét cả bảng).
create index idx_it_assets_created_by on it_assets (created_by);

