create table delivery_projects (
  id                  bigint      generated by default as identity,
  company_id          uuid        not null,
  kind                text        not null,
  lead_id             bigint,
  project_code        text,
  name                text        not null,
  client_name         text        not null default '',
  contact_name        text        not null default '',
  phone               text        not null default '',
  email               text        not null default '',
  address             text        not null default '',
  project_type        text        not null default '',
  status              text        not null default 'nhap',
  start_date          date,
  handover_date       date,
  contract_value_vnd  numeric(18,0) not null default 0,
  approved_budget_vnd numeric(18,0) not null default 0,
  note                text        not null default '',
  created_by          uuid,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint pk_delivery_projects primary key (id),
  constraint fk_delivery_projects_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_delivery_projects_lead_id foreign key (lead_id) references sales_leads (id) on delete set null,
  constraint fk_delivery_projects_project_code foreign key (project_code) references projects (project_code) on delete set null,
  constraint fk_delivery_projects_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_delivery_projects_kind check (kind in ('design', 'construction')),
  constraint ck_delivery_projects_status check (status in ('nhap', 'dang-lam', 'tam-dung', 'hoan-tat')),
  constraint ck_delivery_projects_name check (name <> ''),
  constraint ck_delivery_projects_dates check (handover_date is null or start_date is null or handover_date >= start_date),
  constraint ck_delivery_projects_contract_value_vnd check (contract_value_vnd >= 0),
  constraint ck_delivery_projects_approved_budget_vnd check (approved_budget_vnd >= 0)
);
-- Mỗi khách hàng Kinh doanh có tối đa 1 dự án thiết kế + 1 dự án thi công (tự tạo khi kéo sang giai đoạn đó, không tạo trùng).
create unique index uq_delivery_projects_lead_id_kind on delivery_projects (lead_id, kind) where lead_id is not null;
-- Phục vụ: danh sách dự án theo trang (delivery/postgres.go: ListProjects, lọc cong_ty_id + kind).
create index idx_delivery_projects_company_id_kind on delivery_projects (company_id, kind);
-- Phục vụ: khoá ngoại project_code (xoá dự án QS -> set null).
create index idx_delivery_projects_project_code on delivery_projects (project_code);

