create table delivery_tasks (
  id            bigint      generated by default as identity,
  project_id    bigint      not null,
  phase_id      bigint      not null,
  name          text        not null,
  start_date    date        not null,
  end_date      date        not null,
  progress_pct  numeric(5,2) not null default 0,
  is_critical   boolean     not null default false,
  is_milestone  boolean     not null default false,
  description   text        not null default '',
  depts         text[]      not null default '{}',
  owners        text[]      not null default '{}',
  finance_kind  text,
  planned_date  date,
  amount_vnd    numeric(18,0),
  is_confirmed  boolean     not null default false,
  sort_order    integer     not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint pk_delivery_tasks primary key (id),
  constraint uq_delivery_tasks_id_project_id unique (id, project_id),
  constraint fk_delivery_tasks_project_id foreign key (project_id) references delivery_projects (id) on delete cascade,
  constraint fk_delivery_tasks_phase foreign key (phase_id, project_id) references delivery_phases (id, project_id) on delete cascade,
  constraint ck_delivery_tasks_name check (name <> ''),
  constraint ck_delivery_tasks_dates check (end_date >= start_date),
  constraint ck_delivery_tasks_progress_pct check (progress_pct between 0 and 100),
  constraint ck_delivery_tasks_finance_kind check (finance_kind is null or finance_kind in ('thu', 'chi')),
