create table sales_lead_activities (
  id                  bigint      generated by default as identity,
  lead_id             bigint      not null,
  activity_date       date        not null,
  activity_kind       text        not null,
  title               text        not null,
  content             text        not null default '',
  outcome             text        not null default '',
  next_follow_up_date date,
  next_note           text        not null default '',
  author_name         text        not null default '',
  created_by          uuid,
  created_at          timestamptz not null default now(),
  constraint pk_sales_lead_activities primary key (id),
  constraint fk_sales_lead_activities_lead_id foreign key (lead_id) references sales_leads (id) on delete cascade,
  constraint fk_sales_lead_activities_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_sales_lead_activities_activity_kind check (activity_kind in ('call', 'meeting', 'site', 'zalo', 'email', 'quote', 'note')),
  constraint ck_sales_lead_activities_outcome check (outcome in ('', 'good', 'neutral', 'bad')),
  constraint ck_sales_lead_activities_title check (title <> '')
);
-- Phục vụ: lịch sử chăm sóc của 1 khách hàng (sales/postgres.go: listActivities, lọc lead_id) + khoá ngoại cascade.
create index idx_sales_lead_activities_lead_id on sales_lead_activities (lead_id);

