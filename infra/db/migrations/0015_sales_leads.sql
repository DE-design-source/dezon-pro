-- Kiểm tra trước: 2 bảng chưa tồn tại.
-- Quay lui: drop table sales_lead_activities; drop table sales_leads; (mất dữ liệu kinh doanh đã nhập).

do $$ begin
  if to_regclass('public.sales_leads') is not null or to_regclass('public.sales_lead_activities') is not null then
    raise exception '0015: bảng sales_leads / sales_lead_activities đã có';
  end if;
end $$;

create table sales_leads (
  id                  bigint      generated by default as identity,
  company_id          uuid        not null,
  customer_name       text        not null,
  phone               text        not null default '',
  email               text        not null default '',
  address             text        not null default '',
  lead_source         text        not null default '',
  sales_unit          text        not null default 'dan-dung',
  stage               text        not null default 'tiep-can',
  board_stage         text,
  project_type        text        not null default '',
  scale_note          text        not null default '',
  estimated_value_vnd numeric(18,0) not null default 0,
  categories          text[]      not null default '{}',
  concept_note        text        not null default '',
  note                text        not null default '',
  is_partner_handover boolean     not null default false,
  creator_name        text        not null default '',
  manager_name        text        not null default '',
  assignees           jsonb       not null default '[]',
  handoff             jsonb,
  boq_file_name       text        not null default '',
  project_code        text,
  won_at              timestamptz,
  created_by          uuid,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint pk_sales_leads primary key (id),
  constraint fk_sales_leads_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_sales_leads_project_code foreign key (project_code) references projects (project_code) on delete set null,
  constraint fk_sales_leads_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_sales_leads_customer_name check (customer_name <> ''),
  constraint ck_sales_leads_sales_unit check (sales_unit in ('dan-dung', 'du-an')),
  constraint ck_sales_leads_stage check (stage in ('tiep-can', 'tu-van', 'bao-gia', 'dam-phan', 'chot-hd', 'bao-gia-thi-cong', 'thiet-ke', 'thi-cong', 'truot-thau')),
  constraint ck_sales_leads_board_stage check (board_stage is null or board_stage in
    ('intake', 'concept', 'drafting', 'review', 'approved', 'prep', 'structure', 'finishing', 'acceptance', 'handover')),
  constraint ck_sales_leads_estimated_value_vnd check (estimated_value_vnd >= 0),
  constraint ck_sales_leads_assignees check (jsonb_typeof(assignees) = 'array'),
  constraint ck_sales_leads_handoff check (handoff is null or jsonb_typeof(handoff) = 'object')
);
-- Phục vụ: danh sách khách hàng của công ty (backend/internal/modules/sales/postgres.go: listLeads, lọc cong_ty_id).
create index idx_sales_leads_company_id on sales_leads (company_id);
-- Phục vụ: khoá ngoại project_code (xoá dự án QS -> set null không quét cả bảng).
create index idx_sales_leads_project_code on sales_leads (project_code);

