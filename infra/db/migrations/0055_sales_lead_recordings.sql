-- Kinh doanh: hội thoại ghi lại từ khối "Live" của trang khách hàng - file ghi âm (kho file UPLOAD_DIR) + lời thoại tách theo
-- người nói (Nhân viên / Khách) do Gemini làm nền sau khi tải lên, kèm tóm tắt. Code: kd_ghi_am (db-map.json);
-- module backend/internal/modules/sales (service_recording.go). Bảng con không có company_id: công ty lấy qua sales_leads (lead_id).
-- Số 0055 có chủ ý: 0051 / 0052 thuộc nhánh khác.
-- Kiểm tra trước: bảng chưa tồn tại; bảng cha sales_leads / sales_lead_activities đã có.
-- Quay lui: drop table sales_lead_recordings; (mất danh sách hội thoại đã ghi; file ghi âm trong kho kd-rec/ xoá tay nếu cần,
--           lần chăm sóc đã tạo trong sales_lead_activities giữ nguyên).

do $$ begin
  if to_regclass('public.sales_leads') is null or to_regclass('public.sales_lead_activities') is null then
    raise exception '0055: thiếu bảng sales_leads / sales_lead_activities';
  end if;
  if to_regclass('public.sales_lead_recordings') is not null then
    raise exception '0055: bảng sales_lead_recordings đã có';
  end if;
end $$;

create table sales_lead_recordings (
  id            bigint      generated by default as identity,
  lead_id       bigint      not null,
  kind          text        not null default 'meeting',
  title         text        not null default '',
  duration_sec  integer     not null default 0,
  status        text        not null default 'processing',
  engine        text        not null default 'live',
  model         text        not null default '',
  error_message text        not null default '',
  summary       text        not null default '',
  lines         jsonb       not null default '[]',
  live_lines    jsonb       not null default '[]',
  audio_path    text        not null default '',
  audio_mime    text        not null default '',
  audio_bytes   bigint      not null default 0,
  staff_name    text        not null default '',
  customer_name text        not null default '',
  author_name   text        not null default '',
  activity_id   bigint,
  created_by    uuid,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint pk_sales_lead_recordings primary key (id),
  constraint fk_sales_lead_recordings_lead_id foreign key (lead_id) references sales_leads (id) on delete cascade,
  constraint fk_sales_lead_recordings_activity_id foreign key (activity_id) references sales_lead_activities (id) on delete set null,
  constraint fk_sales_lead_recordings_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_sales_lead_recordings_kind check (kind in ('meeting', 'call')),
  constraint ck_sales_lead_recordings_duration_sec check (duration_sec >= 0),
  constraint ck_sales_lead_recordings_status check (status in ('processing', 'done', 'failed')),
  constraint ck_sales_lead_recordings_engine check (engine in ('gemini', 'live')),
  constraint ck_sales_lead_recordings_lines check (jsonb_typeof(lines) = 'array'),
  constraint ck_sales_lead_recordings_live_lines check (jsonb_typeof(live_lines) = 'array'),
  constraint ck_sales_lead_recordings_audio_bytes check (audio_bytes >= 0)
);
-- Phục vụ: hội thoại của 1 khách hàng (sales/postgres.go: ListRecordings, lọc lead_id) + khoá ngoại cascade.
create index idx_sales_lead_recordings_lead_id on sales_lead_recordings (lead_id);
-- Phục vụ: khoá ngoại activity_id on delete set null (xoá lần chăm sóc / xoá khách -> tìm hội thoại trỏ tới nó).
create index idx_sales_lead_recordings_activity_id on sales_lead_recordings (activity_id) where activity_id is not null;

