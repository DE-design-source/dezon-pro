create table hr_requests (
  id             bigint      generated by default as identity,
  employee_id    bigint      not null,
  request_kind   text        not null,
  leave_kind     text,
  title          text        not null,
  from_date      date        not null,
  to_date        date        not null,
  days           numeric(5,1),
  hours          numeric(5,1),
  reason         text        not null default '',
  approval_steps jsonb       not null default '[]',
  created_by     uuid,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint pk_hr_requests primary key (id),
  constraint fk_hr_requests_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint fk_hr_requests_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_hr_requests_request_kind check (request_kind in ('leave', 'late', 'ot')),
  constraint ck_hr_requests_leave_kind check ((request_kind = 'leave') = (leave_kind is not null)
    and (leave_kind is null or leave_kind in ('annual', 'sick', 'unpaid', 'other'))),
  constraint ck_hr_requests_title check (title <> ''),
  constraint ck_hr_requests_dates check (to_date >= from_date),
  constraint ck_hr_requests_days check (days is null or (days > 0 and days <= 366)),
  constraint ck_hr_requests_hours check (hours is null or (hours > 0 and hours <= 24)),
  constraint ck_hr_requests_approval_steps check (jsonb_typeof(approval_steps) = 'array' and jsonb_array_length(approval_steps) > 0)
);
-- Phục vụ: khoá ngoại employee_id cascade (xoá nhân sự).
create index idx_hr_requests_employee_id on hr_requests (employee_id);

