create table hr_shifts (
  id            bigint      generated by default as identity,
  company_id    uuid        not null,
  shift_code    text        not null,
  shift_name    text        not null,
  start_time    time        not null,
  end_time      time        not null,
  break_minutes integer     not null default 0,
  tone          text        not null default 'primary',
  note          text        not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint pk_hr_shifts primary key (id),
  constraint uq_hr_shifts_company_id_shift_code unique (company_id, shift_code),
  constraint fk_hr_shifts_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_hr_shifts_shift_code check (shift_code ~ '^[A-Z0-9]{1,8}$'),
  constraint ck_hr_shifts_shift_name check (shift_name <> ''),
  constraint ck_hr_shifts_break_minutes check (break_minutes between 0 and 600)
);
-- uq_hr_shifts_company_id_shift_code phục vụ: danh sách ca của công ty (hr/attendance.go: attState) + mã ca duy nhất.

