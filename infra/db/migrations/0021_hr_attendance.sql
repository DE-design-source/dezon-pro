create table hr_work_patterns (
  id          bigint      generated by default as identity,
  employee_id bigint      not null,
  weekday     smallint    not null,
  shift_id    bigint      not null,
  created_at  timestamptz not null default now(),
  constraint pk_hr_work_patterns primary key (id),
  constraint uq_hr_work_patterns_employee_id_weekday unique (employee_id, weekday),
  constraint fk_hr_work_patterns_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint fk_hr_work_patterns_shift_id foreign key (shift_id) references hr_shifts (id) on delete cascade,
  constraint ck_hr_work_patterns_weekday check (weekday between 1 and 7)
);
-- uq_hr_work_patterns_employee_id_weekday phục vụ: lịch của 1 nhân sự + khoá ngoại employee_id cascade.
-- Phục vụ: khoá ngoại shift_id (xoá ca -> xoá các ô lịch dùng ca đó).
create index idx_hr_work_patterns_shift_id on hr_work_patterns (shift_id);

