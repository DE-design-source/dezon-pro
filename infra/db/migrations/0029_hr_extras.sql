-- HR - bổ sung: link CV ứng viên trong kho file, danh mục khoá học + lộ trình học theo công ty, lịch làm việc riêng từng ngày.
-- Code: cột hr_ung_vien.cv_url; bảng hr_khoa_hoc, hr_lo_trinh, hr_lich_ngay (db-map.json); module backend/internal/modules/hr.
-- hr_course_enrollments.course_id từ đây trỏ (mềm) tới hr_courses.id; ghi danh của khoá đã xoá bị bỏ qua khi đọc.
-- Kiểm tra trước: 0021, 0023 đã chạy; cột / bảng chưa có.
-- Quay lui: drop table hr_schedule_overrides, hr_learning_paths, hr_courses; alter table hr_candidates drop column cv_url;

do $$ begin
  if to_regclass('public.hr_candidates') is null or to_regclass('public.hr_shifts') is null then raise exception '0025: cần chạy 0021, 0023 trước'; end if;
  if exists (select 1 from information_schema.columns where table_name = 'hr_candidates' and column_name = 'cv_url')
    or to_regclass('public.hr_courses') is not null or to_regclass('public.hr_learning_paths') is not null
    or to_regclass('public.hr_schedule_overrides') is not null then
    raise exception '0025: cột / bảng đã có';
  end if;
end $$;

alter table hr_candidates add column cv_url text not null default '';
comment on column hr_candidates.cv_url is 'Link of the uploaded CV in the file store (/files/...); empty = only the file name is known.';

create table hr_courses (
  id            bigint       generated by default as identity,
  company_id    uuid         not null,
  title         text         not null,
  category      text         not null default '',
  hours         numeric(6,1) not null default 0,
  course_format text         not null default '',
  is_mandatory  boolean      not null default false,
  tone          text         not null default 'primary',
  created_at    timestamptz  not null default now(),
  updated_at    timestamptz  not null default now(),
  constraint pk_hr_courses primary key (id),
  constraint fk_hr_courses_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_hr_courses_title check (title <> ''),
  constraint ck_hr_courses_hours check (hours >= 0)
);
-- Phục vụ: danh mục khoá học của công ty (hr/talent.go: TalentState).
create index idx_hr_courses_company_id on hr_courses (company_id);

comment on table hr_courses is 'Training course in the company catalog (tenant-owned root table).';
comment on column hr_courses.id is 'Primary key; referenced (soft) by hr_course_enrollments.course_id and hr_learning_paths.course_ids.';
comment on column hr_courses.company_id is 'Owning company; set from the login session, never from the client.';
comment on column hr_courses.title is 'Course title.';
comment on column hr_courses.category is 'Category (Bắt buộc, Chuyên môn...). Open list.';
comment on column hr_courses.hours is 'Duration, hours.';
comment on column hr_courses.course_format is 'Format (Trực tiếp, E-learning, Blended). Open list.';
comment on column hr_courses.is_mandatory is 'Mandatory course: counted in the training compliance KPI.';
comment on column hr_courses.tone is 'Colour tone (frontend palette key).';
comment on column hr_courses.created_at is 'Row creation time.';
comment on column hr_courses.updated_at is 'Last change time (set by the service).';

create table hr_learning_paths (
  id          bigint      generated by default as identity,
  company_id  uuid        not null,
  title       text        not null,
  audience    text        not null default '',
  course_ids  bigint[]    not null default '{}',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint pk_hr_learning_paths primary key (id),
  constraint fk_hr_learning_paths_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_hr_learning_paths_title check (title <> '')
);
-- Phục vụ: lộ trình học của công ty (hr/talent.go: TalentState).
create index idx_hr_learning_paths_company_id on hr_learning_paths (company_id);

comment on table hr_learning_paths is 'Learning path = ordered list of courses to enroll an employee in at once (tenant-owned root table).';
comment on column hr_learning_paths.id is 'Primary key.';
comment on column hr_learning_paths.company_id is 'Owning company; set from the login session, never from the client.';
comment on column hr_learning_paths.title is 'Path title.';
comment on column hr_learning_paths.audience is 'Who it is for (free text).';
comment on column hr_learning_paths.course_ids is 'Ordered hr_courses.id of the same company (soft references, checked by the service; removed when a course is deleted). Display / one-click enrollment only.';
comment on column hr_learning_paths.created_at is 'Row creation time.';
comment on column hr_learning_paths.updated_at is 'Last change time (set by the service).';

create table hr_schedule_overrides (
  id          bigint      generated by default as identity,
  employee_id bigint      not null,
  work_date   date        not null,
  shift_id    bigint,
  created_at  timestamptz not null default now(),
  constraint pk_hr_schedule_overrides primary key (id),
  constraint uq_hr_schedule_overrides_employee_id_work_date unique (employee_id, work_date),
  constraint fk_hr_schedule_overrides_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint fk_hr_schedule_overrides_shift_id foreign key (shift_id) references hr_shifts (id) on delete cascade
);
-- uq_hr_schedule_overrides_employee_id_work_date phục vụ: ghi đè 1 ngày của 1 người + khoá ngoại cascade.
-- Phục vụ: lịch riêng trong khoảng ngày (hr/attendance.go: AttState, lọc work_date) và khoá ngoại shift_id.
create index idx_hr_schedule_overrides_work_date on hr_schedule_overrides (work_date);
create index idx_hr_schedule_overrides_shift_id on hr_schedule_overrides (shift_id);

comment on table hr_schedule_overrides is 'Shift of one employee on one specific date, overriding the weekly pattern (child of hr_employees).';
comment on column hr_schedule_overrides.id is 'Primary key.';
comment on column hr_schedule_overrides.employee_id is 'Employee; rows are deleted with it.';
comment on column hr_schedule_overrides.work_date is 'Date overridden.';
comment on column hr_schedule_overrides.shift_id is 'Shift that day (same company, checked by the service); null = day off. Deleted with the shift (back to the weekly pattern).';
comment on column hr_schedule_overrides.created_at is 'Row creation time.';

