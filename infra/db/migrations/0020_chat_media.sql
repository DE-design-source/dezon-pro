-- ───────────── Tệp đính kèm ─────────────

create table chat_media (
  id           bigint      generated by default as identity,
  uploader_id  bigint      not null,
  media_type   text        not null,
  mime_type    text        not null,
  size_bytes   bigint      not null,
  sha256       text        not null,
  file_name    text,
  object_key   text        not null,
  thumb_key    text,
  status       text        not null default 'pending',
  width        integer,
  height       integer,
  duration_ms  integer,
  waveform     smallint[],
  blurhash     text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint pk_chat_media primary key (id),
  constraint fk_chat_media_uploader_id foreign key (uploader_id) references chat_users (id) on delete restrict,
  constraint uq_chat_media_object_key unique (object_key),
  -- Phục vụ: chống trùng khi xin upload-url cùng nội dung (chat/service_media.go: MediaUploadURL, insert ... on conflict)
  constraint uq_chat_media_uploader_id_sha256_media_type unique (uploader_id, sha256, media_type),
  constraint ck_chat_media_media_type check (media_type in ('image', 'video', 'file', 'voice')),
  constraint ck_chat_media_status check (status in ('pending', 'processing', 'ready', 'failed', 'blocked')),
  constraint ck_chat_media_mime_type check (char_length(mime_type) <= 100 and mime_type ~ '^[a-z0-9.+-]+/[a-z0-9.+-]+$'
    and (media_type = 'file' or (media_type = 'image' and mime_type like 'image/%')
         or (media_type = 'video' and mime_type like 'video/%') or (media_type = 'voice' and mime_type like 'audio/%'))),
  constraint ck_chat_media_size_bytes check (size_bytes > 0 and size_bytes <= 209715200),
  constraint ck_chat_media_sha256 check (sha256 ~ '^[0-9a-f]{64}$'),
  constraint ck_chat_media_file_name check (file_name is null or (char_length(file_name) between 1 and 255 and file_name !~ '[/\\[:cntrl:]]')),
  constraint ck_chat_media_object_key check (object_key like 'chat/m/%'),
  constraint ck_chat_media_width_height check ((width is null) = (height is null) and (width is null or (width between 1 and 100000 and height between 1 and 100000))),
  constraint ck_chat_media_duration_ms check (duration_ms is null or duration_ms between 1 and 86400000),
  constraint ck_chat_media_voice check (media_type <> 'voice' or (duration_ms is not null and waveform is not null)),
  constraint ck_chat_media_waveform check (waveform is null or (media_type = 'voice' and cardinality(waveform) between 1 and 128
    and array_position(waveform, null) is null and 0 <= all (waveform) and 255 >= all (waveform))),
  constraint ck_chat_media_blurhash check (blurhash is null or (media_type in ('image', 'video') and char_length(blurhash) between 6 and 100)),
  constraint ck_chat_media_thumb_key check (thumb_key is null or media_type in ('image', 'video'))
);

-- Phục vụ: hạn mức dung lượng tải lên trong 24 giờ của một người (chat/service_media.go: MediaUploadURL, quotaUsed)
create index idx_chat_media_uploader_id_created_at on chat_media (uploader_id, created_at);
-- Phục vụ: dọn tệp chưa gửi / tải dở / xử lý treo quá hạn (chat/service_media.go: janitorOnce)
create index idx_chat_media_status_updated_at on chat_media (status, updated_at);

