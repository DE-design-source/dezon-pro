  check (message_type in ('text', 'system', 'image', 'video', 'file', 'voice'));
alter table chat_messages drop constraint ck_chat_messages_content;
alter table chat_messages add constraint ck_chat_messages_content check (char_length(content) <= 4000 and case
  when message_type in ('text', 'system') then btrim(content) <> ''
  when message_type = 'voice' then content = ''
  else true end);
alter table chat_messages add constraint ck_chat_messages_media_id
  check ((message_type in ('image', 'video', 'file', 'voice')) = (media_id is not null));
alter table chat_messages add constraint ck_chat_messages_file_name
  check (file_name is null or (message_type = 'file' and char_length(file_name) between 1 and 255 and file_name !~ '[/\\[:cntrl:]]'));
