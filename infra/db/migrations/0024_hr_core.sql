create table hr_unit_members (
  id            bigint      generated by default as identity,
  unit_id       bigint      not null,
  employee_id   bigint      not null,
  role_title    text        not null default '',
  time_pct      numeric(5,2) not null default 0,
  allowance_vnd numeric(18,0) not null default 0,
  created_at    timestamptz not null default now(),
  constraint pk_hr_unit_members primary key (id),
  constraint uq_hr_unit_members_unit_id_employee_id unique (unit_id, employee_id),
  constraint fk_hr_unit_members_unit_id foreign key (unit_id) references hr_org_units (id) on delete cascade,
  constraint fk_hr_unit_members_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint ck_hr_unit_members_time_pct check (time_pct >= 0 and time_pct <= 90),
  constraint ck_hr_unit_members_allowance_vnd check (allowance_vnd >= 0)
);
-- uq_hr_unit_members_unit_id_employee_id phục vụ: thành viên của 1 đơn vị + khoá ngoại unit_id cascade.
-- Phục vụ: khoá ngoại employee_id cascade (xoá nhân sự).
create index idx_hr_unit_members_employee_id on hr_unit_members (employee_id);

