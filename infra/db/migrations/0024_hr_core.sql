create table hr_employees (
  id                bigint      generated by default as identity,
  company_id        uuid        not null,
  employee_code     text        not null,
  full_name         text        not null,
  gender            text        not null default '',
  birth_date        date,
  dept_key          text        not null,
  job_title         text        not null default '',
  job_level         text        not null default 'Nhân viên',
  employment_status text        not null default 'probation',
  join_date         date        not null,
  leave_date        date,
  manager_id        bigint,
  work_site         text        not null default '',
  contract_type     text        not null default '',
  salary_vnd        numeric(18,0) not null default 0,
  phone             text        not null default '',
  email             text        not null default '',
  details           jsonb       not null default '{}',
  created_by        uuid,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint pk_hr_employees primary key (id),
  constraint uq_hr_employees_id_company_id unique (id, company_id),
  constraint uq_hr_employees_company_id_employee_code unique (company_id, employee_code),
  constraint fk_hr_employees_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_employees_dept foreign key (company_id, dept_key) references hr_org_units (company_id, unit_key) on delete no action,
  constraint fk_hr_employees_manager foreign key (manager_id, company_id) references hr_employees (id, company_id) on delete set null (manager_id),
  constraint fk_hr_employees_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_hr_employees_employee_code check (employee_code <> ''),
  constraint ck_hr_employees_full_name check (full_name <> ''),
  constraint ck_hr_employees_employment_status check (employment_status in ('probation', 'active', 'left')),
  constraint ck_hr_employees_manager_id check (manager_id is null or manager_id <> id),
  constraint ck_hr_employees_salary_vnd check (salary_vnd >= 0),
  constraint ck_hr_employees_details check (jsonb_typeof(details) = 'object')
);
-- uq_hr_employees_company_id_employee_code phục vụ: danh sách nhân sự của công ty (hr/service.go: load) + mã NV duy nhất.
-- Phục vụ: khoá ngoại ghép phòng ban (xoá đơn vị -> kiểm còn nhân sự không quét cả bảng).
create index idx_hr_employees_company_id_dept_key on hr_employees (company_id, dept_key);
-- Phục vụ: khoá ngoại quản lý (xoá nhân sự -> set null cấp dưới) + chuyển cấp dưới khi nghỉ việc (hr/service.go: reassignReports).
create index idx_hr_employees_manager_id on hr_employees (manager_id);

