-- HR (trang /cham-cong): cơ cấu tổ chức, hồ sơ nhân sự, kiêm nhiệm. Trước đây chỉ có dữ liệu mẫu trong trình duyệt.
-- Code: hr_don_vi, hr_nhan_vien, hr_kiem_nhiem (db-map.json); module backend/internal/modules/hr.
-- Đơn vị và nhân sự cùng công ty nhờ khoá ngoại ghép (company_id, ...): phòng ban, quản lý, trưởng đơn vị không trỏ sang công ty khác.
-- hr_kiem_nhiem là bảng con (không mang company_id, công ty xét qua đơn vị); nhân sự cùng công ty do service kiểm.
-- Self-reference / phòng ban dùng ON DELETE NO ACTION (chặn như RESTRICT nhưng kiểm cuối câu lệnh) để xoá công ty
-- xoá được cả cây đơn vị trong một câu lệnh.
-- Kiểm tra trước: 3 bảng chưa tồn tại.
-- Quay lui: drop table hr_unit_members, hr_employees, hr_org_units cascade; (mất dữ liệu HR đã nhập).

do $$ begin
  if to_regclass('public.hr_org_units') is not null or to_regclass('public.hr_employees') is not null
    or to_regclass('public.hr_unit_members') is not null then
    raise exception '0020: bảng hr_org_units / hr_employees / hr_unit_members đã có';
  end if;
end $$;

create table hr_org_units (
  id                       bigint      generated by default as identity,
  company_id               uuid        not null,
  unit_key                 text        not null,
  label                    text        not null,
  unit_name                text        not null default '',
  unit_kind                text        not null,
  parent_key               text,
  group_link               text,
  head_employee_id         bigint,
  tone                     text        not null default 'primary',
  description              text        not null default '',
  is_appointed_from_parent boolean     not null default false,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  constraint pk_hr_org_units primary key (id),
  constraint uq_hr_org_units_company_id_unit_key unique (company_id, unit_key),
  constraint fk_hr_org_units_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_org_units_parent foreign key (company_id, parent_key) references hr_org_units (company_id, unit_key) on delete no action,
  constraint ck_hr_org_units_unit_key check (unit_key ~ '^[a-z0-9][a-z0-9_]{0,59}$'),
  constraint ck_hr_org_units_label check (label <> ''),
  constraint ck_hr_org_units_unit_kind check (unit_kind in ('governance', 'board', 'exec', 'dept', 'subsidiary')),
  constraint ck_hr_org_units_parent_key check (parent_key is null or parent_key <> unit_key),
  constraint ck_hr_org_units_group_link check (group_link is null or (group_link in ('holding', 'mother') and parent_key is null))
);
-- uq_hr_org_units_company_id_unit_key phục vụ: danh sách đơn vị của công ty (hr/service.go: load, lọc cong_ty_id) + khoá ngoại ghép.

