-- HR - phân quyền thật: hồ sơ nhân sự gắn với tài khoản đăng nhập + vai trò HR; ma trận quyền theo công ty.
-- Code: cột hr_nhan_vien.tai_khoan_id / vai_tro_hr, bảng hr_bao_mat (db-map.json); module backend/internal/modules/hr (access.go).
-- Nhật ký HR ghi vào audit_logs có sẵn (action 'hr.<phân hệ>.<thao tác>'), không thêm bảng.
-- Tài khoản phải cùng công ty với hồ sơ: service kiểm (users không có khoá ghép (id, company_id)).
-- Kiểm tra trước: 0020 đã chạy, cột / bảng chưa có.
-- Quay lui: drop table hr_security_settings; alter table hr_employees drop column user_id, drop column hr_role;

do $$ begin
  if to_regclass('public.hr_employees') is null then raise exception '0024: cần chạy 0020_hr_core trước'; end if;
  if exists (select 1 from information_schema.columns where table_name = 'hr_employees' and column_name in ('user_id', 'hr_role'))
    or to_regclass('public.hr_security_settings') is not null then
    raise exception '0024: cột user_id / hr_role hoặc bảng hr_security_settings đã có';
  end if;
end $$;

alter table hr_employees
  add column user_id uuid,
  add column hr_role text not null default 'employee',
  add constraint fk_hr_employees_user_id foreign key (user_id) references users (id) on delete set null,
  add constraint ck_hr_employees_hr_role check (hr_role in ('sysadmin', 'hradmin', 'manager', 'employee'));
-- Phục vụ: tìm hồ sơ của tài khoản đang đăng nhập (hr/access.go: access) + 1 tài khoản chỉ gắn 1 hồ sơ.
create unique index uq_hr_employees_user_id on hr_employees (user_id) where user_id is not null;

comment on column hr_employees.user_id is 'Login account of this employee (same company, checked by the service); null = not linked. Set null when the account is deleted.';
comment on column hr_employees.hr_role is 'HR role of the linked account: sysadmin / hradmin (whole company) / manager (own department) / employee (self). Company admins are always sysadmin.';

create table hr_security_settings (
  id          bigint      generated by default as identity,
  company_id  uuid        not null,
  perms       jsonb       not null,
  mask_salary boolean     not null default true,
  updated_by  uuid,
  updated_at  timestamptz not null default now(),
  constraint pk_hr_security_settings primary key (id),
  constraint uq_hr_security_settings_company_id unique (company_id),
  constraint fk_hr_security_settings_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_security_settings_updated_by foreign key (updated_by) references users (id) on delete set null,
  constraint ck_hr_security_settings_perms check (jsonb_typeof(perms) = 'object')
);
-- uq_hr_security_settings_company_id phục vụ: đọc ma trận quyền của công ty ở mỗi lệnh HR (hr/access.go) + 1 dòng / công ty.

comment on table hr_security_settings is 'HR permission matrix and security options of a company, one row per company (tenant-owned root table). No row = built-in defaults.';
comment on column hr_security_settings.id is 'Primary key.';
comment on column hr_security_settings.company_id is 'Owning company; set from the login session, never from the client.';
comment on column hr_security_settings.perms is 'Document read/written whole: {"hradmin"|"manager"|"employee": {"employees"|"attendance"|"payroll"|"recruit"|"performance"|"security": ["view","create","edit","delete","approve","export"]}}. sysadmin always has everything.';
comment on column hr_security_settings.mask_salary is 'Hide salary amounts by default in the payroll screens.';
comment on column hr_security_settings.updated_by is 'User who saved last; set null if the user is deleted.';
comment on column hr_security_settings.updated_at is 'Last change time (set by the service).';

-- Xác minh sau
do $$ begin
  if to_regclass('public.hr_security_settings') is null then raise exception '0024: thiếu bảng hr_security_settings'; end if;
  if not exists (select 1 from pg_indexes where indexname = 'uq_hr_employees_user_id') then raise exception '0024: thiếu uq_hr_employees_user_id'; end if;
end $$;
