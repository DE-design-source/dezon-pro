-- HR - địa điểm làm việc theo công ty (thay danh sách mẫu cố định trong giao diện): tên, toạ độ + bán kính cho chấm công GPS,
-- cờ công trường (phụ cấp công trường, lịch mẫu T2–T7). Code: hr_dia_diem (db-map.json); module backend/internal/modules/hr (attendance.go).
-- hr_employees.work_site vẫn là tên địa điểm (chuỗi tự do, tham chiếu mềm theo tên) - không đổi dữ liệu cũ.
-- Kiểm tra trước: bảng chưa tồn tại. Quay lui: drop table hr_work_sites;

do $$ begin
  if to_regclass('public.hr_work_sites') is not null then raise exception '0026: bảng hr_work_sites đã có'; end if;
end $$;

create table hr_work_sites (
  id            bigint       generated by default as identity,
  company_id    uuid         not null,
  site_name     text         not null,
  latitude      numeric(9,6),
  longitude     numeric(9,6),
  radius_m      integer      not null default 200,
  is_field_site boolean      not null default false,
  created_at    timestamptz  not null default now(),
  updated_at    timestamptz  not null default now(),
  constraint pk_hr_work_sites primary key (id),
  constraint uq_hr_work_sites_company_id_site_name unique (company_id, site_name),
  constraint fk_hr_work_sites_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_hr_work_sites_site_name check (site_name <> ''),
  constraint ck_hr_work_sites_coords check ((latitude is null) = (longitude is null)
    and (latitude is null or (latitude between -90 and 90 and longitude between -180 and 180))),
  constraint ck_hr_work_sites_radius_m check (radius_m between 10 and 100000)
);
-- uq_hr_work_sites_company_id_site_name phục vụ: danh sách địa điểm của công ty (hr/attendance.go: AttState) + tên duy nhất.

comment on table hr_work_sites is 'Work location of a company: name, GPS point and radius for self check-in, field-site flag (tenant-owned root table).';
comment on column hr_work_sites.id is 'Primary key.';
comment on column hr_work_sites.company_id is 'Owning company; set from the login session, never from the client.';
comment on column hr_work_sites.site_name is 'Location name; hr_employees.work_site / hr_job_openings.work_site refer to it by name (soft reference).';
comment on column hr_work_sites.latitude is 'GPS latitude; null = no GPS check-in at this site.';
comment on column hr_work_sites.longitude is 'GPS longitude; null together with latitude.';
comment on column hr_work_sites.radius_m is 'Check-in radius, metres.';
comment on column hr_work_sites.is_field_site is 'Construction site: site allowance in payroll, Mon–Sat template schedule.';
comment on column hr_work_sites.created_at is 'Row creation time.';
comment on column hr_work_sites.updated_at is 'Last change time (set by the service).';

