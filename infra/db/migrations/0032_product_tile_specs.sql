do $$ begin
  if to_regclass('public.product_tile_specs') is not null then raise exception '0032: bảng product_tile_specs đã có'; end if;
  if to_regclass('public.product_catalog') is null then raise exception '0032: thiếu view product_catalog'; end if;
end $$;

create table product_tile_specs (
  product_id bigint not null,
  tile_body text,
  water_absorption text,
  slip_resistance text,
  box_packing text,
  constraint pk_product_tile_specs primary key (product_id),
  constraint fk_product_tile_specs_product_id foreign key (product_id) references products (id) on delete cascade
);
comment on table product_tile_specs is 'Tile (Gạch ốp lát) specifications of a product (1-1 with products; row exists only when at least one value is set).';
comment on column product_tile_specs.tile_body is 'Tile spec (code: xuong_gach)';
comment on column product_tile_specs.water_absorption is 'Tile spec (code: do_hut_nuoc)';
comment on column product_tile_specs.slip_resistance is 'Tile spec (code: chong_tron)';
comment on column product_tile_specs.box_packing is 'Tile spec (code: quy_cach_hop)';
comment on column product_tile_specs.product_id is 'Product (products.id); row deleted with the product.';

