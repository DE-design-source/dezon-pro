-- 4 thông số còn lại dùng chung cột có sẵn: kich_thuoc (size), be_mat (surface_finish), do_day (thickness), mau_sac (color).
-- Kiểm tra trước: chưa có bảng product_tile_specs; view product_catalog đang có.
