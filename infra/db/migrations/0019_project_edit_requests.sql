create table project_edit_requests (
  id              bigint      generated by default as identity,
  company_id      uuid        not null,
  project_code    text        not null,
  project_name    text        not null default '',
  requester_id    uuid,
  requester_name  text        not null default '',
  changes         jsonb       not null,
  old_values      jsonb       not null default '{}',
  status          text        not null default 'pending',
  note            text,
  resolver_name   text,
  resolved_at     timestamptz,
  resolution_note text,
  created_at      timestamptz not null default now(),
  constraint pk_project_edit_requests primary key (id),
  constraint fk_project_edit_requests_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_project_edit_requests_project_code foreign key (project_code) references projects (project_code) on delete cascade,
  constraint fk_project_edit_requests_requester_id foreign key (requester_id) references users (id) on delete set null,
  constraint ck_project_edit_requests_status check (status in ('pending', 'approved', 'rejected')),
  constraint ck_project_edit_requests_changes check (jsonb_typeof(changes) = 'object'),
  constraint ck_project_edit_requests_old_values check (jsonb_typeof(old_values) = 'object')
);
-- Phục vụ: danh sách phiếu của 1 dự án (trang chi tiết) + khoá ngoại project_code (xoá dự án -> cascade không quét cả bảng).
create index idx_project_edit_requests_project_code on project_edit_requests (project_code);
-- Phục vụ: danh sách phiếu chờ duyệt của công ty (người duyệt), mới nhất trước.
create index idx_project_edit_requests_company_id_status on project_edit_requests (company_id, status);
-- Phục vụ: khoá ngoại requester_id (xoá tài khoản -> set null).
create index idx_project_edit_requests_requester_id on project_edit_requests (requester_id);

