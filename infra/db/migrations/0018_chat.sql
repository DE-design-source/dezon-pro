-- Chat MVP (backend/CHAT.md, giai đoạn MVP): tài khoản chat theo số điện thoại + OTP, thiết bị + refresh token,
-- bạn bè / lời mời / chặn, hội thoại 1-1 và nhóm, tin nhắn văn bản có seq tăng dần theo hội thoại, con trỏ đã nhận / đã xem.
-- Tài khoản chat KHÔNG phải bảng users của QS và KHÔNG thuộc công ty nào (dùng chung mọi công ty như Zalo): không có
-- company_id, không vào TenantTables. Code: chat_* trong db-map.json; module backend/internal/modules/chat (SQL thô qua pgx).
-- Kiểm tra trước: 9 bảng chưa tồn tại.
-- Quay lui: drop table chat_messages, chat_direct_pairs, chat_conversation_members, chat_conversations, chat_friendships,
--   chat_otp_codes, chat_refresh_tokens, chat_devices, chat_users; (mất dữ liệu chat).

do $$ begin
  if to_regclass('public.chat_users') is not null or to_regclass('public.chat_devices') is not null
     or to_regclass('public.chat_refresh_tokens') is not null or to_regclass('public.chat_otp_codes') is not null
     or to_regclass('public.chat_friendships') is not null or to_regclass('public.chat_conversations') is not null
     or to_regclass('public.chat_conversation_members') is not null or to_regclass('public.chat_direct_pairs') is not null
     or to_regclass('public.chat_messages') is not null then
    raise exception '0018: bảng chat_* đã có';
  end if;
end $$;

-- ───────────── Tài khoản, thiết bị, phiên ─────────────

create table chat_users (
  id                 bigint      generated by default as identity,
  phone              text        not null,
  -- phone chỉ gồm '+' và chữ số (ck_chat_users_phone) nên phone::bytea đúng bằng các byte UTF-8 của số
  -- (convert_to là STABLE, không dùng được trong cột GENERATED)
  phone_hash         text        generated always as (encode(sha256(phone::bytea), 'hex')) stored,
  display_name       text        not null,
  show_read_receipts boolean     not null default true,
  last_seen_at       timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint pk_chat_users primary key (id),
  constraint uq_chat_users_phone unique (phone),
  constraint ck_chat_users_phone check (phone ~ '^\+[1-9][0-9]{7,14}$'),
  constraint ck_chat_users_display_name check (btrim(display_name) <> '' and char_length(display_name) <= 100)
);
-- Phục vụ: đồng bộ danh bạ bằng hash số điện thoại (backend/internal/modules/chat/postgres.go: matchContacts).
create index idx_chat_users_phone_hash on chat_users (phone_hash);

comment on table chat_users is 'Chat account (identity = phone number). Separate from QS users and not tenant-scoped: one account across all companies.';
comment on column chat_users.id is 'Primary key (user_id in the chat API).';
comment on column chat_users.phone is 'Phone number in E.164 form (+84901234567), normalized by the service; unique.';
comment on column chat_users.phone_hash is 'Derived: lowercase hex SHA-256 of phone; contact matching without sending raw numbers.';
comment on column chat_users.display_name is 'Name shown to other users, 1..100 characters.';
comment on column chat_users.show_read_receipts is 'False: other members never see this user''s read pointer (last_read_seq); the user''s own devices still do.';
comment on column chat_users.last_seen_at is 'Time the user went offline (last connection closed + grace period); null = never.';
comment on column chat_users.created_at is 'Account creation time (first successful OTP verification).';
comment on column chat_users.updated_at is 'Last profile change time (set by the service).';

create table chat_devices (
  id           bigint      generated by default as identity,
  user_id      bigint      not null,
  platform     text        not null,
  device_name  text        not null default '',
  push_kind    text,
  push_token   text,
  last_seen_at timestamptz,
  created_at   timestamptz not null default now(),
  constraint pk_chat_devices primary key (id),
  constraint fk_chat_devices_user_id foreign key (user_id) references chat_users (id) on delete cascade,
  constraint ck_chat_devices_platform check (platform in ('ios', 'android', 'web', 'desktop')),
  constraint ck_chat_devices_device_name check (char_length(device_name) <= 200),
  constraint ck_chat_devices_push_kind check (push_kind in ('webpush', 'fcm', 'apns')),
  constraint ck_chat_devices_push_token check ((push_kind is null) = (push_token is null))
);
-- Phục vụ: thiết bị nhận push của một người (chat/postgres.go: pushDevices) + khoá ngoại cascade.
create index idx_chat_devices_user_id on chat_devices (user_id);
-- Phục vụ: gỡ cùng một push subscription khỏi thiết bị khác khi đăng ký lại (chat/postgres.go: setPushToken).
create index idx_chat_devices_push_token on chat_devices (push_token) where push_token is not null;

comment on table chat_devices is 'A signed-in device (one row per successful OTP login). Deleting the row = logout: refresh tokens and push token go with it.';
comment on column chat_devices.id is 'Primary key (device_id, also the "did" claim of the access token).';
comment on column chat_devices.user_id is 'Owning chat account.';
comment on column chat_devices.platform is 'ios / android / web / desktop.';
comment on column chat_devices.device_name is 'Free-text label (browser / OS), at most 200 characters.';
comment on column chat_devices.push_kind is 'Push channel of push_token: webpush / fcm / apns; null = no push for this device.';
comment on column chat_devices.push_token is 'webpush: the PushSubscription JSON string; fcm / apns: the device token. Null together with push_kind.';
comment on column chat_devices.last_seen_at is 'Last token refresh or WebSocket authentication from this device.';
comment on column chat_devices.created_at is 'Login time.';

create table chat_refresh_tokens (
  id         bigint      generated by default as identity,
  device_id  bigint      not null,
  token_hash text        not null,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now(),
  constraint pk_chat_refresh_tokens primary key (id),
  constraint fk_chat_refresh_tokens_device_id foreign key (device_id) references chat_devices (id) on delete cascade,
  constraint uq_chat_refresh_tokens_token_hash unique (token_hash),
  constraint ck_chat_refresh_tokens_token_hash check (token_hash ~ '^[0-9a-f]{64}$')
);
-- Phục vụ: dọn token hết hạn của thiết bị khi refresh (chat/postgres.go: rotateRefresh) + khoá ngoại cascade.
create index idx_chat_refresh_tokens_device_id on chat_refresh_tokens (device_id);

comment on table chat_refresh_tokens is 'Refresh tokens of a device, stored hashed. Rotation: each refresh marks the presented token used and issues a new row; a used token presented again = reuse -> device revoked.';
comment on column chat_refresh_tokens.id is 'Primary key.';
comment on column chat_refresh_tokens.device_id is 'Device the token belongs to.';
comment on column chat_refresh_tokens.token_hash is 'Lowercase hex SHA-256 of the opaque token (the token itself is never stored).';
comment on column chat_refresh_tokens.expires_at is 'Expiry (issue time + CHAT_REFRESH_TTL_DAYS).';
comment on column chat_refresh_tokens.used_at is 'Set when the token was rotated; null = still usable.';
comment on column chat_refresh_tokens.created_at is 'Issue time.';

create table chat_otp_codes (
  id           bigint      generated by default as identity,
  phone        text        not null,
  code_hash    text        not null,
  request_ip   text        not null default '',
  attempts     integer     not null default 0,
  expires_at   timestamptz not null,
  consumed_at  timestamptz,
  locked_until timestamptz,
  created_at   timestamptz not null default now(),
  constraint pk_chat_otp_codes primary key (id),
  constraint ck_chat_otp_codes_phone check (phone ~ '^\+[1-9][0-9]{7,14}$'),
  constraint ck_chat_otp_codes_attempts check (attempts >= 0)
);
-- Phục vụ: mã mới nhất / đếm số lần gửi trong 1 giờ / khoá của một số (chat/postgres.go: otpState, latestOTP).
create index idx_chat_otp_codes_phone_created_at on chat_otp_codes (phone, created_at desc);
-- Phục vụ: đếm số lần gửi OTP trong 1 giờ theo IP (chat/postgres.go: otpState).
create index idx_chat_otp_codes_request_ip_created_at on chat_otp_codes (request_ip, created_at desc);

comment on table chat_otp_codes is 'One-time login codes sent by SMS; also the source of the OTP rate limits (rows per phone / IP per hour). Rows older than 24 h are deleted on the next request of the phone.';
comment on column chat_otp_codes.id is 'Primary key.';
comment on column chat_otp_codes.phone is 'E.164 phone the code was sent to. Soft reference: the account may not exist yet, no FK.';
comment on column chat_otp_codes.code_hash is 'Lowercase hex HMAC-SHA256(server OTP secret, phone || '':'' || code); the code itself is never stored.';
comment on column chat_otp_codes.request_ip is 'Client IP of the request (rate limit per IP); empty when unknown.';
comment on column chat_otp_codes.attempts is 'Wrong verification attempts against this code.';
comment on column chat_otp_codes.expires_at is 'created_at + 5 minutes.';
comment on column chat_otp_codes.consumed_at is 'Set when verified successfully; a consumed code is never accepted again.';
comment on column chat_otp_codes.locked_until is 'Set when attempts reach 5: the phone cannot request or verify codes until then (15 minutes).';
comment on column chat_otp_codes.created_at is 'Request time.';

-- ───────────── Bạn bè / chặn ─────────────

create table chat_friendships (
  user_id    bigint      not null,
  friend_id  bigint      not null,
  status     text        not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pk_chat_friendships primary key (user_id, friend_id),
  constraint fk_chat_friendships_user_id foreign key (user_id) references chat_users (id) on delete cascade,
  constraint fk_chat_friendships_friend_id foreign key (friend_id) references chat_users (id) on delete cascade,
  constraint ck_chat_friendships_status check (status in ('pending', 'accepted', 'blocked')),
  constraint ck_chat_friendships_friend_id check (user_id <> friend_id)
);
-- Phục vụ: lời mời kết bạn gửi tới tôi (chat/postgres.go: friendRequests, lọc friend_id + status) + khoá ngoại cascade.
create index idx_chat_friendships_friend_id_status on chat_friendships (friend_id, status);

comment on table chat_friendships is 'Directed relation user -> friend. pending = user sent a friend request; accepted = friends (both directions have an accepted row); blocked = user blocked friend.';
comment on column chat_friendships.user_id is 'Account that owns this side of the relation.';
comment on column chat_friendships.friend_id is 'The other account.';
comment on column chat_friendships.status is 'pending / accepted / blocked.';
comment on column chat_friendships.created_at is 'Time the relation row was created (friend request time for pending).';
comment on column chat_friendships.updated_at is 'Last status change (set by the service).';

-- ───────────── Hội thoại, thành viên, tin nhắn ─────────────

create table chat_conversations (
  id                bigint      generated by default as identity,
  conversation_type text        not null,
  name              text,
  last_seq          bigint      not null default 0,
  last_message_at   timestamptz,
  created_by        bigint      not null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint pk_chat_conversations primary key (id),
  constraint fk_chat_conversations_created_by foreign key (created_by) references chat_users (id) on delete restrict,
  constraint ck_chat_conversations_conversation_type check (conversation_type in ('direct', 'group')),
  constraint ck_chat_conversations_name check ((conversation_type = 'group') = (name is not null)
    and (name is null or (btrim(name) <> '' and char_length(name) <= 100))),
  constraint ck_chat_conversations_last_seq check (last_seq >= 0)
);

comment on table chat_conversations is 'A 1-1 (direct) or group conversation. last_seq is the per-conversation message counter: allocated with UPDATE ... SET last_seq = last_seq + 1 RETURNING inside the send transaction (row lock = ordering).';
comment on column chat_conversations.id is 'Primary key (conversation_id).';
comment on column chat_conversations.conversation_type is 'direct / group.';
comment on column chat_conversations.name is 'Group name (1..100 characters); null for direct conversations.';
comment on column chat_conversations.last_seq is 'Derived: seq of the newest message (= max(chat_messages.seq) of the conversation, 0 = none). Written only by the send path.';
comment on column chat_conversations.last_message_at is 'Derived: created_at of the newest message; null = no message yet. Orders the conversation list.';
comment on column chat_conversations.created_by is 'Account that created the conversation (chat accounts are not deleted in the MVP: restrict).';
comment on column chat_conversations.created_at is 'Creation time.';
comment on column chat_conversations.updated_at is 'Bumped on every message, rename and membership change; drives GET /chat/sync.';

create table chat_conversation_members (
  conversation_id    bigint      not null,
  user_id            bigint      not null,
  member_role        text        not null default 'member',
  last_read_seq      bigint      not null default 0,
  last_delivered_seq bigint      not null default 0,
  muted_until        timestamptz,
  left_at            timestamptz,
  joined_at          timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint pk_chat_conversation_members primary key (conversation_id, user_id),
  constraint fk_chat_conversation_members_conversation_id foreign key (conversation_id) references chat_conversations (id) on delete cascade,
  constraint fk_chat_conversation_members_user_id foreign key (user_id) references chat_users (id) on delete cascade,
  constraint ck_chat_conversation_members_member_role check (member_role in ('owner', 'admin', 'member')),
  constraint ck_chat_conversation_members_last_read_seq check (last_read_seq >= 0),
  constraint ck_chat_conversation_members_last_delivered_seq check (last_delivered_seq >= 0)
);
-- Phục vụ: danh sách hội thoại / sync / tổng chưa đọc của một người (chat/postgres.go: listConversations, syncRows, badge).
create index idx_chat_conversation_members_user_id on chat_conversation_members (user_id);

comment on table chat_conversation_members is 'Membership of an account in a conversation, with its delivered / read pointers (seq). Rows are kept after leaving (left_at) so /sync can report the removal.';
comment on column chat_conversation_members.conversation_id is 'Conversation.';
comment on column chat_conversation_members.user_id is 'Member account.';
comment on column chat_conversation_members.member_role is 'owner / admin / member (direct conversations: member).';
comment on column chat_conversation_members.last_read_seq is 'Every message with seq <= this was seen by the member. Never decreases while active.';
comment on column chat_conversation_members.last_delivered_seq is 'Every message with seq <= this reached a device of the member. Never decreases; the service keeps it >= last_read_seq.';
comment on column chat_conversation_members.muted_until is 'No push for this conversation until then; ''infinity'' = muted forever; null or past = not muted.';
comment on column chat_conversation_members.left_at is 'Null = active member; set when the member left or was removed (re-adding clears it).';
comment on column chat_conversation_members.joined_at is 'Time the member (re)joined; earliest-joined admin / member inherits ownership when the owner leaves.';
comment on column chat_conversation_members.updated_at is 'Bumped when this member''s pointers, mute or membership change; drives GET /chat/sync.';

create table chat_direct_pairs (
  user_low        bigint not null,
  user_high       bigint not null,
  conversation_id bigint not null,
  constraint pk_chat_direct_pairs primary key (user_low, user_high),
  constraint fk_chat_direct_pairs_user_low foreign key (user_low) references chat_users (id) on delete cascade,
  constraint fk_chat_direct_pairs_user_high foreign key (user_high) references chat_users (id) on delete cascade,
  constraint fk_chat_direct_pairs_conversation_id foreign key (conversation_id) references chat_conversations (id) on delete cascade,
  constraint uq_chat_direct_pairs_conversation_id unique (conversation_id),
  constraint ck_chat_direct_pairs_user_high check (user_low < user_high)
);

comment on table chat_direct_pairs is 'At most one direct conversation per pair of accounts: the primary key on (min id, max id) stops two concurrent creates from making two conversations.';
comment on column chat_direct_pairs.user_low is 'Smaller account id of the pair.';
comment on column chat_direct_pairs.user_high is 'Larger account id of the pair.';
comment on column chat_direct_pairs.conversation_id is 'The direct conversation of the pair.';

create table chat_messages (
  id              bigint      generated by default as identity,
  conversation_id bigint      not null,
  seq             bigint      not null,
  client_msg_id   uuid,
  sender_id       bigint      not null,
  message_type    text        not null,
  content         text        not null,
  created_at      timestamptz not null default now(),
  constraint pk_chat_messages primary key (id),
  constraint fk_chat_messages_conversation_id foreign key (conversation_id) references chat_conversations (id) on delete cascade,
  constraint fk_chat_messages_sender_id foreign key (sender_id) references chat_users (id) on delete restrict,
  -- Phục vụ: đọc lịch sử theo khoảng seq + tin cuối của hội thoại (chat/postgres.go: listMessages, listConversations)
  constraint uq_chat_messages_conversation_id_seq unique (conversation_id, seq),
  -- Phục vụ: chống trùng khi client gửi lại cùng client_msg_id (chat/postgres.go: findByClientID; thay message_dedup của CHAT.md)
  constraint uq_chat_messages_conversation_id_sender_id_client_msg_id unique (conversation_id, sender_id, client_msg_id),
  constraint ck_chat_messages_seq check (seq > 0),
  constraint ck_chat_messages_message_type check (message_type in ('text', 'system')),
  constraint ck_chat_messages_client_msg_id check ((message_type = 'system') = (client_msg_id is null)),
  constraint ck_chat_messages_content check (btrim(content) <> '' and char_length(content) <= 4000)
);

comment on table chat_messages is 'Messages of all conversations (MVP keeps them in PostgreSQL; CHAT.md section 4 allows moving them to Cassandra later with the same keys).';
comment on column chat_messages.id is 'Primary key (message_id).';
comment on column chat_messages.conversation_id is 'Conversation.';
comment on column chat_messages.seq is 'Position in the conversation: 1, 2, 3... without gaps (allocated from chat_conversations.last_seq).';
comment on column chat_messages.client_msg_id is 'UUID generated by the sending client; resending the same id returns the stored message (idempotent). Null for system messages.';
comment on column chat_messages.sender_id is 'Sender (for system messages: the member who performed the action).';
comment on column chat_messages.message_type is 'text / system (group created, members added / removed / left, renamed, role changed).';
comment on column chat_messages.content is 'Message text, 1..4000 characters, not blank.';
comment on column chat_messages.created_at is 'Time the message was stored (the "sent" time).';

