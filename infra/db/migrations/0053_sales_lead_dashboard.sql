-- Số 0053 có chủ ý: 0051 / 0052 thuộc nhánh khác.
-- Kiểm tra trước: cột / 4 bảng chưa tồn tại.
-- Quay lui: drop table sales_lead_insights, sales_lead_tasks, sales_lead_appointments, sales_lead_scores;
--           alter table sales_leads drop column stage_changed_at; (mất điểm, lịch hẹn, task, phân tích đã lưu).

do $$ begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'sales_leads' and column_name = 'stage_changed_at') then
    raise exception '0053: cột sales_leads.stage_changed_at đã có';
  end if;
  if to_regclass('public.sales_lead_scores') is not null or to_regclass('public.sales_lead_appointments') is not null
     or to_regclass('public.sales_lead_tasks') is not null or to_regclass('public.sales_lead_insights') is not null then
    raise exception '0053: bảng sales_lead_scores / sales_lead_appointments / sales_lead_tasks / sales_lead_insights đã có';
  end if;
end $$;

-- Thời điểm vào giai đoạn hiện tại ("Đã ở giai đoạn này N ngày"). Dòng cũ: lấy updated_at (gần đúng nhất có được).
alter table sales_leads add column stage_changed_at timestamptz;
update sales_leads set stage_changed_at = updated_at;
alter table sales_leads alter column stage_changed_at set default now();
alter table sales_leads alter column stage_changed_at set not null;
comment on column sales_leads.stage_changed_at is 'When the lead entered its current stage (set by the service when stage changes; backfilled from updated_at).';

create table sales_lead_scores (
  lead_id    bigint      not null,
  checks     jsonb       not null default '{}',
  history    jsonb       not null default '[]',
  updated_by text        not null default '',
  updated_at timestamptz not null default now(),
  constraint pk_sales_lead_scores primary key (lead_id),
  constraint fk_sales_lead_scores_lead_id foreign key (lead_id) references sales_leads (id) on delete cascade,
  constraint ck_sales_lead_scores_checks check (jsonb_typeof(checks) = 'object'),
  constraint ck_sales_lead_scores_history check (jsonb_typeof(history) = 'array')
);
-- Khoá chính lead_id đã là index (khoá ngoại cascade, đọc điểm của 1 khách).

comment on table sales_lead_scores is 'Deal score checklist of a sales lead: 6 criteria x 4 questions (child of sales_leads, one row per lead).';
comment on column sales_lead_scores.lead_id is 'Owning lead (primary key); row is deleted with it.';
comment on column sales_lead_scores.checks is 'Document read/written whole: {"<criterion key>": [bool x4]} - which questions are answered yes.';
comment on column sales_lead_scores.history is 'Document read/written whole: [{"at": ISO time, "score": deal score}] appended on each save (capped by the service).';
comment on column sales_lead_scores.updated_by is 'Display name of the last editor (snapshot).';
comment on column sales_lead_scores.updated_at is 'Last save time.';

create table sales_lead_appointments (
  id               bigint      generated by default as identity,
  lead_id          bigint      not null,
  appointment_date date        not null,
  start_time       text        not null default '',
  end_time         text        not null default '',
  title            text        not null,
  meeting_mode     text        not null default '',
  place            text        not null default '',
  goal             text        not null default '',
  members          jsonb       not null default '[]',
  prep_items       jsonb       not null default '[]',
  status           text        not null default 'planned',
  author_name      text        not null default '',
  created_by       uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint pk_sales_lead_appointments primary key (id),
  constraint fk_sales_lead_appointments_lead_id foreign key (lead_id) references sales_leads (id) on delete cascade,
  constraint fk_sales_lead_appointments_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_sales_lead_appointments_title check (title <> ''),
  constraint ck_sales_lead_appointments_start_time check (start_time = '' or start_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  constraint ck_sales_lead_appointments_end_time check (end_time = '' or end_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  constraint ck_sales_lead_appointments_members check (jsonb_typeof(members) = 'array'),
  constraint ck_sales_lead_appointments_prep_items check (jsonb_typeof(prep_items) = 'array'),
  constraint ck_sales_lead_appointments_status check (status in ('planned', 'done', 'cancelled'))
);
-- Phục vụ: lịch hẹn của 1 khách hàng (sales/postgres.go: ListAppointments, lọc lead_id) + khoá ngoại cascade.
create index idx_sales_lead_appointments_lead_id on sales_lead_appointments (lead_id);

