create table hr_performance_reviews (
  id             bigint      generated by default as identity,
  employee_id    bigint      not null,
  review_period  text        not null,
  review_state   text        not null default 'self',
  self_scores    jsonb,
  manager_scores jsonb,
  self_note      text        not null default '',
  manager_note   text        not null default '',
  updated_at     timestamptz not null default now(),
  constraint pk_hr_performance_reviews primary key (id),
  constraint uq_hr_performance_reviews_employee_id_review_period unique (employee_id, review_period),
  constraint fk_hr_performance_reviews_employee_id foreign key (employee_id) references hr_employees (id) on delete cascade,
  constraint ck_hr_performance_reviews_review_state check (review_state in ('self', 'manager', 'done')),
  constraint ck_hr_performance_reviews_scores check ((self_scores is null or jsonb_typeof(self_scores) = 'object')
