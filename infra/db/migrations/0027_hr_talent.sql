create table hr_candidates (
  id                bigint      generated by default as identity,
  job_id            bigint      not null,
  full_name         text        not null,
  email             text        not null default '',
  phone             text        not null default '',
  lead_source       text        not null default '',
  stage             text        not null default 'applied',
  applied_date      date        not null,
  cv_name           text        not null default '',
  experience_note   text        not null default '',
  reviews           jsonb       not null default '[]',
  interviews        jsonb       not null default '[]',
  hired_employee_id bigint,
  hired_date        date,
  created_by        uuid,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint pk_hr_candidates primary key (id),
  constraint fk_hr_candidates_job_id foreign key (job_id) references hr_job_openings (id) on delete cascade,
  constraint fk_hr_candidates_hired_employee_id foreign key (hired_employee_id) references hr_employees (id) on delete set null,
  constraint fk_hr_candidates_created_by foreign key (created_by) references users (id) on delete set null,
  constraint ck_hr_candidates_full_name check (full_name <> ''),
  constraint ck_hr_candidates_stage check (stage in ('applied', 'screening', 'interview', 'offer', 'hired', 'rejected')),
  constraint ck_hr_candidates_reviews check (jsonb_typeof(reviews) = 'array'),
