create table hr_job_openings (
  id             bigint      generated by default as identity,
  company_id     uuid        not null,
  jd_id          bigint      not null,
  title          text        not null,
  dept_key       text        not null default '',
  quantity       integer     not null default 1,
  work_site      text        not null default '',
  salary_text    text        not null default '',
  deadline_date  date,
  opening_status text        not null default 'open',
  channels       text[]      not null default '{}',
  description    text        not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint pk_hr_job_openings primary key (id),
  constraint uq_hr_job_openings_id_company_id unique (id, company_id),
  constraint fk_hr_job_openings_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_hr_job_openings_jd foreign key (jd_id) references hr_job_descriptions (id) on delete restrict,
  constraint ck_hr_job_openings_title check (title <> ''),
  constraint ck_hr_job_openings_quantity check (quantity between 1 and 1000),
  constraint ck_hr_job_openings_opening_status check (opening_status in ('open', 'paused', 'closed'))
);
-- Phục vụ: tin tuyển dụng của công ty (hr/talent.go: TalentState).
