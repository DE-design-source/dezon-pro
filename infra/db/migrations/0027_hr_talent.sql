-- HR - tuyển dụng + hiệu suất & đào tạo: thư viện JD, tin tuyển dụng, ứng viên (kèm đánh giá / lịch phỏng vấn), mục tiêu OKR,
-- đánh giá nhân sự theo kỳ, ghi danh khoá học. Code: hr_jd, hr_tin_tuyen, hr_ung_vien, hr_muc_tieu, hr_danh_gia, hr_ghi_danh
-- (db-map.json); module backend/internal/modules/hr (talent.go).
-- dept_key ở JD / tin / mục tiêu là tham chiếu mềm tới hr_org_units.unit_key (JD, tin cũ giữ được khi đơn vị bị xoá / đổi).
-- Danh mục khoá học, lộ trình học vẫn cố định ở giao diện (COURSES, LEARNING_PATHS): course_id là mã trong danh mục đó.
-- Kiểm tra trước: 0020 đã chạy, 6 bảng chưa tồn tại.
-- Quay lui: drop table hr_course_enrollments, hr_performance_reviews, hr_objectives, hr_candidates, hr_job_openings, hr_job_descriptions;

do $$ begin
  if to_regclass('public.hr_employees') is null then raise exception '0023: cần chạy 0020_hr_core trước'; end if;
  if to_regclass('public.hr_job_descriptions') is not null or to_regclass('public.hr_job_openings') is not null
    or to_regclass('public.hr_candidates') is not null or to_regclass('public.hr_objectives') is not null
    or to_regclass('public.hr_performance_reviews') is not null or to_regclass('public.hr_course_enrollments') is not null then
    raise exception '0023: bảng tuyển dụng / hiệu suất HR đã có';
  end if;
end $$;

create table hr_job_descriptions (
  id           bigint      generated by default as identity,
  company_id   uuid        not null,
  jd_code      text        not null default '',
  title        text        not null,
  dept_key     text        not null default '',
  job_level    text        not null default '',
  salary_text  text        not null default '',
  summary      text        not null default '',
  duties       text[]      not null default '{}',
  requirements text[]      not null default '{}',
  benefits     text[]      not null default '{}',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint pk_hr_job_descriptions primary key (id),
  constraint fk_hr_job_descriptions_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint ck_hr_job_descriptions_title check (title <> '')
);
-- Phục vụ: thư viện JD của công ty (hr/talent.go: TalentState, lọc cong_ty_id).
create index idx_hr_job_descriptions_company_id on hr_job_descriptions (company_id);

