-- Chat: tin nhắn hẹn giờ. Người dùng hẹn một tin văn bản (kèm @nhắc tên / trả lời tin như gửi thường) trong hội thoại mình
-- đang tham gia; tới send_at máy chủ gửi hộ y như người đó tự gửi (lưu tin, phân phối realtime, push), kể cả khi họ offline.
-- Worker của module chat (service_scheduled.go) lấy dòng tới hạn bằng FOR UPDATE SKIP LOCKED, gửi với client_msg_id suy ra từ id
-- (chống trùng khi chạy nhiều instance / chết giữa chừng). Không thuộc công ty (như mọi bảng chat_*), không vào TenantTables.
-- Code: module backend/internal/modules/chat (SQL thô qua pgx); db-map.json: chat_hen_gio (chat_scheduled_messages).
-- Kiểm tra trước: bảng chat_users / chat_conversations đã có (0018), chưa có bảng chat_scheduled_messages.
-- Quay lui: drop table chat_scheduled_messages; delete from schema_migrations where version = '0048';
--   (mất các tin hẹn giờ chưa gửi; tin đã gửi vẫn nằm trong chat_messages)

do $$ begin
  if to_regclass('public.chat_users') is null or to_regclass('public.chat_conversations') is null then
    raise exception '0048: thiếu bảng chat_users / chat_conversations (chạy 0018 trước)';
  end if;
  if to_regclass('public.chat_scheduled_messages') is not null then raise exception '0048: bảng chat_scheduled_messages đã có'; end if;
end $$;

create table chat_scheduled_messages (
  id                  bigint      generated by default as identity,
  user_id             bigint      not null,
  conversation_id     bigint      not null,
  content             text        not null,
  mentions            jsonb,
  reply_to_message_id bigint,
  send_at             timestamptz not null,
  status              text        not null default 'pending',
  error               text,
  message_id          bigint,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  sent_at             timestamptz,
  constraint pk_chat_scheduled_messages primary key (id),
  constraint fk_chat_scheduled_messages_user_id foreign key (user_id) references chat_users (id) on delete cascade,
  constraint fk_chat_scheduled_messages_conversation_id foreign key (conversation_id) references chat_conversations (id) on delete cascade,
  constraint ck_chat_scheduled_messages_content check (btrim(content) <> '' and char_length(content) <= 4000),
  constraint ck_chat_scheduled_messages_mentions check (mentions is null or (jsonb_typeof(mentions) = 'array' and jsonb_array_length(mentions) between 1 and 50)),
  constraint ck_chat_scheduled_messages_status check (status in ('pending', 'sent', 'canceled', 'failed')),
  constraint ck_chat_scheduled_messages_sent check ((status = 'sent') = (sent_at is not null and message_id is not null))
);

-- Phục vụ: worker lấy tin tới hạn (chat/service_scheduled.go: sendOneScheduled, status = 'pending' and send_at <= now).
create index idx_chat_scheduled_messages_send_at on chat_scheduled_messages (send_at) where status = 'pending';
-- Phục vụ: danh sách tin hẹn của tôi trong một hội thoại + đếm giới hạn 50 (chat/service_scheduled.go: ListScheduled,
-- CreateScheduled) + khoá ngoại user_id on delete cascade.
create index idx_chat_scheduled_messages_user_id_conversation_id on chat_scheduled_messages (user_id, conversation_id);
-- Phục vụ: khoá ngoại conversation_id on delete cascade (xoá hội thoại không quét cả bảng).
create index idx_chat_scheduled_messages_conversation_id on chat_scheduled_messages (conversation_id);

