    raise exception '0052: thiếu bảng access_grants';
  end if;
  if not exists (select 1 from pg_constraint where conname = 'uq_access_grants_company_id_user_id') then
    raise exception '0052: thiếu ràng buộc uq_access_grants_company_id_user_id';
  end if;
end $$;
