-- Phân quyền 3 cấp (2026-11-20, roadmap N21): quản trị hệ thống (super) đặt TRẦN quyền cho từng công ty và từng
-- quản trị công ty; quản trị công ty cấp cho nhân viên tập con quyền của chính mình. Quyền theo Module > Tab > Thao tác
-- (view / create / edit / delete / approve / export), danh mục ở backend/internal/modules/access/catalog.json.
-- Quyền thực = giao các cấp, tính lúc đọc (thu ở cấp trên thì cấp dưới tự mất).
-- Không có dòng = giữ cách cũ: công ty theo companies.features, admin được hết trong trần công ty,
-- nhân viên theo users.permissions.
-- Code: phan_quyen (db-map.json); module backend/internal/modules/access.
-- Kiểm tra trước: bảng chưa tồn tại.
-- Quay lui: drop table access_grants; (mất ma trận phân quyền, mọi tài khoản về cách cũ).

do $$ begin
  if to_regclass('public.access_grants') is not null then
    raise exception '0052: bảng access_grants đã có';
  end if;
end $$;

create table access_grants (
  id          bigint      generated by default as identity,
  company_id  uuid        not null,
  user_id     uuid,
  grants      jsonb       not null default '{}',
  granted_by  uuid,
  updated_by  text        not null default '',
  updated_at  timestamptz not null default now(),
  constraint pk_access_grants primary key (id),
  constraint fk_access_grants_company_id foreign key (company_id) references companies (id) on delete cascade,
  constraint fk_access_grants_user_id foreign key (user_id) references users (id) on delete cascade,
  constraint fk_access_grants_granted_by foreign key (granted_by) references users (id) on delete set null,
  constraint uq_access_grants_company_id_user_id unique nulls not distinct (company_id, user_id),
  constraint ck_access_grants_grants check (jsonb_typeof(grants) = 'object')
);
-- Phục vụ: quyền của 1 tài khoản (backend/internal/modules/access/postgres.go: UserRow) + khoá ngoại user_id.
create index idx_access_grants_user_id on access_grants (user_id);
-- Phục vụ: khoá ngoại granted_by (xoá tài khoản người cấp).
create index idx_access_grants_granted_by on access_grants (granted_by);

comment on table access_grants is 'Three-level access matrix (N21): company ceiling (user_id null) and per-account grants. No row = legacy behaviour (companies.features / users.permissions).';
comment on column access_grants.id is 'Primary key.';
comment on column access_grants.company_id is 'Owning company.';
comment on column access_grants.user_id is 'Account the grants apply to; null = ceiling of the whole company (set by system super admin).';
comment on column access_grants.grants is 'Granted rights {"<module>": {"<tab>": ["view", "create", "edit", "delete", "approve", "export"]}}; tab "*" = every tab of the module.';
comment on column access_grants.granted_by is 'Account that set these grants; a company admin here also caps the staff rights at read time. Null if deleted.';
comment on column access_grants.updated_by is 'Username of the last editor.';
comment on column access_grants.updated_at is 'Last change time.';

-- Xác minh sau
do $$
begin
